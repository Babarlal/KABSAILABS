/* ============================================================
   Proof gallery
   Renders our published case studies from /assets/data/portfolio-builds.json
   into any <div data-gallery="<set>"> on the page. Every card links to its
   page under /case-studies/. The JSON and the pages are both generated by
   scripts/build-case-studies.js, so a set can only name published builds.

     <div data-gallery="rag"></div>
     <div data-gallery="workflow" data-gallery-cta="See the workflows we've shipped"></div>

   Five builds or fewer render as a static grid of .gcard, because a handful of
   real builds reads better standing still. More than five render as the dark
   two column scroller, .port-glass, which the CSS pauses on hover and stops
   entirely under prefers-reduced-motion.

   On /case-studies the list is already in the HTML (data-gallery="all"), so
   this script only wires the category filters there. It still renders the list
   itself if the markup is ever missing.

   The sets below are explicit slug lists rather than a filter over the category
   field, because each page was designed around particular builds. Editing a set
   here changes that page's gallery.
   ============================================================ */
