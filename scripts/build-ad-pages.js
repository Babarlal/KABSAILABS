#!/usr/bin/env node
/* ============================================================
   Build the paid traffic copies of SEO pages.

     node scripts/build-ad-pages.js          rebuild
     node scripts/build-ad-pages.js --check  fail if anything is out of date

   Writes:
   - lp/shopify-inventory-sync.html      from services/industries/ecommerce.html
   - lp/shopify-support-automation.html  from services/shopify-support-automation.html

   Google Ads points at the /lp/ copy; the source page stays the indexed one with
   the full menu. The copy is generated, never edited, so the sections and copy
   cannot drift apart: edit the source page, then run this.

   What changes in the copy:
   - noindex, follow, and the source page stays the canonical
   - no structured data (it describes the canonical page, not this one)
   - data-layout="ad": main.js paints a logo and one booking button, no menu,
     and a footer with Privacy and Terms only
   - the lead source on the form, so ad leads are told apart in the sheet
   - links that leave the page are removed, except an allowlist that opens in a
     new tab. A new outbound link on the source page fails the build here rather
     than leaking ad visitors off the page.

   RUN THIS AFTER EDITING ANY SOURCE PAGE LISTED BELOW. Where the pages are also in
   build-critical-css.js, run that next, then this script's --check.
   ============================================================ */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
process.chdir(ROOT);
const CHECK = process.argv.includes('--check');

/* canonical: the source page's own canonical, checked so a copy can never point at
   the wrong page. faq: the opening tag of the FAQ section, where blog links may stay.
   strip: page specific removals, run before the link check. */
const PAGES = [
  {
    src: 'services/industries/ecommerce.html',
    out: 'lp/shopify-inventory-sync.html',
    path: '/lp/shopify-inventory-sync',
    source: 'shopify_inventory_sync_lp',
    canonical: 'https://www.kabsailabs.com/services/industries/ecommerce',
    faq: '<section class="faq wrap">',
    strip(h) {
      // The oversell calculator is another page; on an ad page the form is the only next step.
      h = h.replace(/\s*<p class="hero-alt">[\s\S]*?<\/p>/, '');
      // "Read ..." blog pointers in the gap list leave the page and are not in the FAQ.
      const [ga, gb] = section(h, '<section class="picker wrap" id="gaps">');
      return h.slice(0, ga) + h.slice(ga, gb).replace(/ Read <a href="\/blog\/[^"]+">[^<]*<\/a>\./g, '') + h.slice(gb);
    }
  },
  {
    src: 'services/shopify-support-automation.html',
    out: 'lp/shopify-support-automation.html',
    path: '/lp/shopify-support-automation',
    source: 'shopify_support_automation_lp',
    canonical: 'https://www.kabsailabs.com/services/shopify-support-automation',
    faq: '<section class="faq wrap sp-white" aria-labelledby="faqTitle">',
    // Every link on the source page is an in-page anchor or Privacy, so nothing to strip.
    strip(h) { return h; }
  }
];

/* Outbound links the ad copy keeps. Each opens in a new tab so the visitor still
   has this page. The FAQ blog links are kept only inside the FAQ section. */
const KEEP_ANYWHERE = [/^\/privacy$/, /^\/terms$/, /^\/case-studies$/, /^https:\/\/calendly\.com\//];
const KEEP_IN_FAQ = [/^\/blog\//];

function once(html, from, to, label) {
  const n = html.split(from).length - 1;
  if (n !== 1) throw new Error(label + ': expected 1 match, found ' + n);
  return html.replace(from, to);
}

function section(html, open) {
  const a = html.indexOf(open);
  if (a === -1) throw new Error('section not found: ' + open);
  const b = html.indexOf('</section>', a);
  return [a, b + '</section>'.length];
}

function newTab(tag) {
  if (!/\starget=/.test(tag)) tag = tag.replace(/^<a\b/, '<a target="_blank"');
  if (!/\srel=/.test(tag)) tag = tag.replace(/^<a\b/, '<a rel="noopener"');
  return tag;
}

function build(p) {
  /* LF throughout, so a CRLF checkout cannot break the literal '\n' matches below. */
  let h = fs.readFileSync(p.src, 'utf8').replace(/\r\n/g, '\n');

  h = once(h, '<head>\n', '<head>\n<!-- GENERATED by scripts/build-ad-pages.js from ' + p.src + '. Do not edit; edit the source and rebuild. -->\n', 'banner');
  h = h.replace(/(<meta name="description"[^>]*>\n)/, '$1<meta name="robots" content="noindex, follow">\n');
  if (!h.includes('<meta name="robots" content="noindex, follow">')) throw new Error('robots meta not inserted');
  if (!h.includes('<link rel="canonical" href="' + p.canonical + '">')) throw new Error(p.src + ': canonical missing on source');
  h = h.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\n/, '');

  h = h.replace(/<body data-path="[^"]*" data-layout="[^"]*">/, '<body data-path="' + p.path + '" data-layout="ad">');
  if (!h.includes('data-layout="ad"')) throw new Error('body attributes not rewritten');

  h = h.replace(/(<div id="site-header">)<noscript>[\s\S]*?<\/noscript>(<\/div>)/,
    '$1<noscript><nav class="nojs-nav" aria-label="Primary"><a href="#top">KABS AI LABS</a><a href="#book">Book the free audit</a></nav></noscript>$2');
  h = h.replace(/(<div id="site-footer">)<noscript>[\s\S]*?<\/noscript>(<\/div>)/,
    '$1<noscript><nav class="nojs-nav" aria-label="Secondary"><a href="/privacy" target="_blank" rel="noopener">Privacy</a><a href="/terms" target="_blank" rel="noopener">Terms</a></nav></noscript>$2');

  h = h.replace(/data-source="[^"]*"/, 'data-source="' + p.source + '"');
  if (!h.includes('data-source="' + p.source + '"')) throw new Error(p.src + ': no data-source on the booking section');

  h = p.strip(h);

  const [fa, fb] = section(h, p.faq);
  const bad = [];
  h = h.replace(/<a\b[^>]*>/g, (tag, at) => {
    const m = tag.match(/\shref="([^"]*)"/);
    if (!m) return tag;
    const href = m[1];
    if (href.startsWith('#')) return tag;
    const inFaq = at > fa && at < fb;
    if (KEEP_ANYWHERE.some(r => r.test(href)) || (inFaq && KEEP_IN_FAQ.some(r => r.test(href)))) return newTab(tag);
    bad.push(href);
    return tag;
  });
  if (bad.length) throw new Error(p.src + ' has links that would leave the ad page: ' + bad.join(', ') + '. Allow them in build-ad-pages.js or strip them.');

  return h;
}

/* The inlined critical CSS belongs to build-critical-css.js, not to this script. A copy
   inherits the source's block on its first build; after that the copy keeps its own,
   which build-critical-css.js extracts from the copy itself (it has no announcement bar
   and a different header, so its first screen is not the source's). Without this the
   two scripts would each keep rewriting the other's output. build-critical-css.js
   --check is what catches a stale block. */
const CRIT_START = '<!-- critical:start';
const CRIT_END = '<!-- critical:end -->';
function critBlock(html) {
  const a = html.indexOf(CRIT_START);
  if (a === -1) return null;
  const b = html.indexOf(CRIT_END, a);
  return b === -1 ? null : [a, b + CRIT_END.length];
}
function keepOwnCritical(html, current) {
  const mine = current && critBlock(current), theirs = critBlock(html);
  if (!mine || !theirs) return html;
  return html.slice(0, theirs[0]) + current.slice(mine[0], mine[1]) + html.slice(theirs[1]);
}

let stale = 0;
for (const p of PAGES) {
  const current = fs.existsSync(p.out) ? fs.readFileSync(p.out, 'utf8').replace(/\r\n/g, '\n') : null;
  const html = keepOwnCritical(build(p), current);
  if (CHECK) {
    if (current !== html) { console.error('STALE ' + p.out + ', run node scripts/build-ad-pages.js'); stale++; }
    continue;
  }
  if (current !== html) { fs.writeFileSync(p.out, html); console.log('wrote ' + p.out); }
  else console.log('unchanged ' + p.out);
}
if (CHECK) {
  if (stale) process.exit(1);
  console.log('ad pages are current');
}
