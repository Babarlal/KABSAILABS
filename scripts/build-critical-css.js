#!/usr/bin/env node
/* ============================================================
   Inline the above-the-fold CSS and make the stylesheets non-blocking.

     node scripts/build-critical-css.js          rebuild
     node scripts/build-critical-css.js --check  fail if it is out of date

   RUN THIS AFTER EDITING ANY STYLESHEET OR ANY PAGE IN PAGES BELOW, and after
   scripts/minify-assets.js, since it reads the .min.css files the pages link.

   Why: the homepage blocked first paint on three stylesheets, ~150KB raw. A
   browser will not paint a single pixel until every one of them has arrived.
   PageSpeed measured about 2.5s of that on mobile.

   What it does, per page:
     1. loads the page in headless Chromium with every sheet applied
     2. keeps the rules that style something in the first viewport
     3. inlines those into <head>, between the critical:start/end markers
     4. rewrites each local <link rel="stylesheet"> to
        <link rel="preload" as="style" onload="this.rel='stylesheet'"> plus a
        <noscript> copy, so it downloads at high priority but blocks nothing

   Three things this deliberately does NOT do:
     - it never touches the Google Fonts <link>. That one is third party and
       still blocks paint; it is the floor on what any of this can achieve.
     - it leaves the <link> elements exactly where they were. The cascade is
       document order of the elements, not the order they finish loading, so
       styles -> audit-patches -> pages-green survives the swap untouched.
     - the inlined <style> goes BEFORE the first link, so every rule in it is
       overridden by the identical rule in the real sheet once that lands.

   Extraction runs at three widths (390, 768, 1280) and keeps the union. One
   HTML file is served to every device, so critical CSS built only at phone
   width would leave desktop with a flash of unstyled content.
   ============================================================ */
const fs = require('fs');
const path = require('path');
const http = require('http');
const url = require('url');

const ROOT = path.resolve(__dirname, '..');
process.chdir(ROOT);

/* The pages this runs on. The mechanism is page-agnostic; the list is short
   because every page added here has to be eyeballed once before it ships. */
const PAGES = [
  'index.html',
  'lp/inventory-sync.html',
  'lp/oversell-risk.html'
];

const WIDTHS = [390, 768, 1280];
/* 20 samples 250ms apart, so every width is observed across a 5s window. */
const SAMPLES = 20;
const SAMPLE_GAP = 250;
const CHECK = process.argv.includes('--check');
const START = '<!-- critical:start  GENERATED by scripts/build-critical-css.js, do not hand-edit -->';
const END = '<!-- critical:end -->';
const CR = String.fromCharCode(13), LF = String.fromCharCode(10);

/* ---------- a local server, so Chromium sees the real absolute /assets paths ---------- */
const TYPES = { '.html': 'text/html;charset=utf-8', '.css': 'text/css;charset=utf-8',
  '.js': 'text/javascript;charset=utf-8', '.json': 'application/json', '.svg': 'image/svg+xml',
  '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.ico': 'image/x-icon',
  '.woff2': 'font/woff2', '.xml': 'application/xml', '.txt': 'text/plain' };

function serve() {
  return new Promise(res => {
    const s = http.createServer((req, rsp) => {
      let p = decodeURIComponent(url.parse(req.url).pathname);
      if (p.endsWith('/')) p += 'index.html';
      let f = path.join(ROOT, p);
      if (!fs.existsSync(f) || fs.statSync(f).isDirectory()) {
        if (fs.existsSync(f + '.html')) f += '.html';
        else if (fs.existsSync(path.join(f, 'index.html'))) f = path.join(f, 'index.html');
        else { rsp.writeHead(404); return rsp.end('404'); }
      }
      rsp.writeHead(200, { 'content-type': TYPES[path.extname(f).toLowerCase()] || 'application/octet-stream',
                           'cache-control': 'no-store' });
      rsp.end(fs.readFileSync(f));
    });
    s.listen(0, '127.0.0.1', () => res({ server: s, port: s.address().port }));
  });
}

/* ---------- the extractor, stringified into the page ---------- */
/* eslint-disable */
function collect() {
  var VH = window.innerHeight;
  var keep = {};                       // "sheetIndex.path" -> true
  var fonts = {};                      // animation names referenced by kept rules

  /* A selector can only be tested against the DOM once the parts that describe a
     state or an invented box are removed: a:hover matches nothing right now, but
     the rule still paints the link. ::before and friends have no element of their
     own, so they are judged by their host. */
  function testable(sel) {
    return sel
      .replace(/::?(hover|focus|focus-visible|focus-within|active|visited|target|checked|indeterminate|disabled|enabled|read-only|read-write|placeholder-shown|autofill|default|valid|invalid|required|optional|user-invalid|any-link|link|defined|fullscreen|popover-open|open)\b/g, '')
      .replace(/::(before|after|first-line|first-letter|selection|placeholder|marker|backdrop|file-selector-button|-webkit-[a-z-]+|-moz-[a-z-]+)\b/g, '')
      .trim();
  }

  /* Rules that must survive whatever the DOM looks like right now. :root carries
     every custom property, so losing it loses the whole palette. The header and
     footer are painted by main.js after this measurement, and their reserved
     height is the thing stopping the page jumping when they land. */
  function unconditional(sel) {
    return /(^|,)\s*(:root|html|body|\*)\s*($|,|\{)/.test(sel + '{')
        || sel.indexOf('#site-header') !== -1
        || sel.indexOf('#site-footer') !== -1;
  }

  /* display:none collapses an element to DOMRect(0,0,0,0): no size AND no position,
     because there is no box to position. That is the signature to look for. Testing
     size alone is wrong and was the cause of a build that would not reproduce: the
     homepage's .scroll-hint is a 1px rule animating through scaleY(0), so roughly one
     sample in twenty caught it at zero height and pulled it into the critical set even
     though it sits at y=881, well below the fold. An element scaled to nothing still
     knows where it is; a hidden one does not. visibility:hidden keeps its box too, so
     it is judged on position like anything else, which is correct: the mega-menu panel
     is hidden but sits inside the header, above the fold, and is kept for that reason. */
  function hidden(r) {
    return r.width === 0 && r.height === 0 && r.top === 0 && r.left === 0;
  }

  /* Two ways a rule earns its place. The obvious one is that it styles something
     visible in the first viewport. The other is that it styles something the page is
     currently hiding -- display:none on the mobile nav, for one. Dropping those rules
     does not hide less, it hides nothing: the first paint rendered the whole collapsed
     navigation as an expanded list, and the page shifted 0.67 when the real sheet landed
     and put it away. hidden() above defines what counts as hidden. */
  function matchesAbove(selectorText) {
    if (unconditional(selectorText)) return true;
    var parts = selectorText.split(',');
    for (var i = 0; i < parts.length; i++) {
      var s = testable(parts[i]);
      if (!s) return true;                       // e.g. a bare ::selection rule
      var els;
      try { els = document.querySelectorAll(s); } catch (e) { return true; }  // keep what we cannot judge
      for (var j = 0; j < els.length && j < 200; j++) {
        var r = els[j].getBoundingClientRect();
        if (hidden(r)) return true;                                          // hidden now, must stay hidden
        if (r.top < VH && r.bottom > -1) return true;                        // visible above the fold
      }
    }
    return false;
  }

  function noteAnimations(style) {
    var v = (style.getPropertyValue('animation-name') || '') + ' ' + (style.getPropertyValue('animation') || '');
    v.split(/[\s,]+/).forEach(function (w) { if (w) fonts[w] = true; });
  }

  function walk(rules, sheetIndex, prefix) {
    for (var i = 0; i < rules.length; i++) {
      var r = rules[i], id = prefix + i;
      if (r.type === 1) {                                        // style rule
        if (matchesAbove(r.selectorText)) { keep[sheetIndex + '.' + id] = true; noteAnimations(r.style); }
      } else if (r.type === 4 || r.type === 12) {                // @media, @supports
        walk(r.cssRules || [], sheetIndex, id + '-');
      } else if (r.type === 5) {                                 // @font-face
        keep[sheetIndex + '.' + id] = true;
      }
    }
  }

  var sheets = document.styleSheets;
  for (var si = 0; si < sheets.length; si++) {
    var rules;
    try { rules = sheets[si].cssRules; } catch (e) { continue; }  // cross-origin: Google Fonts
    if (!rules) continue;
    walk(rules, si, '');
  }

  /* Keyframes come along only if something kept above actually plays them. */
  for (var si2 = 0; si2 < sheets.length; si2++) {
    var rs;
    try { rs = sheets[si2].cssRules; } catch (e) { continue; }
    if (!rs) continue;
    for (var k = 0; k < rs.length; k++) {
      if (rs[k].type === 7 && fonts[rs[k].name]) keep[si2 + '.' + k] = true;
    }
  }

  var hrefs = [];
  for (var h = 0; h < sheets.length; h++) hrefs.push(sheets[h].href || '(inline)');
  return { keep: Object.keys(keep), hrefs: hrefs };
}

/* Serialise the union back out, in sheet order then rule order. */
function emit(keepSet) {
  var out = [];
  var sheets = document.styleSheets;

  function text(rules, sheetIndex, prefix) {
    var buf = '';
    for (var i = 0; i < rules.length; i++) {
      var r = rules[i], id = prefix + i, key = sheetIndex + '.' + id;
      if (r.type === 1 || r.type === 5 || r.type === 7) {
        if (keepSet.indexOf(key) !== -1) buf += r.cssText + '\n';
      } else if (r.type === 4 || r.type === 12) {
        var inner = text(r.cssRules || [], sheetIndex, id + '-');
        if (inner) {
          buf += (r.type === 4 ? '@media ' + r.conditionText : '@supports ' + r.conditionText)
               + '{\n' + inner + '}\n';
        }
      }
    }
    return buf;
  }

  for (var si = 0; si < sheets.length; si++) {
    var rules;
    try { rules = sheets[si].cssRules; } catch (e) { continue; }
    if (!rules) continue;
    if (!sheets[si].href) continue;                 // skip our own inlined <style>
    out.push(text(rules, si, ''));
  }
  return out.join('');
}
/* eslint-enable */

/* ---------- HTML rewriting ---------- */

/* Read the local stylesheet links out of a page in document order, whichever
   form they are currently in, so this script is safe to run over its own output. */
function readLinks(html) {
  const links = [];
  const re = /<link\b[^>]*href="(\/assets\/css\/[^"]+)"[^>]*>/g;
  let m;
  while ((m = re.exec(html))) {
    const tag = m[0];
    if (/rel="stylesheet"/.test(tag) || /rel="preload"/.test(tag)) {
      if (!links.some(l => l.href === m[1])) links.push({ href: m[1], index: m.index });
    }
  }
  return links;
}

/* Put the page back into its plain blocking form, so rebuilds are idempotent. */
function revert(html) {
  let t = html;
  const s = t.indexOf(START);
  if (s !== -1) {
    const e = t.indexOf(END, s);
    if (e !== -1) t = t.slice(0, s) + t.slice(e + END.length).replace(/^\n/, '');
  }
  t = t.replace(/<link rel="preload" as="style" href="(\/assets\/css\/[^"]+)"[^>]*>\n<noscript><link rel="stylesheet" href="\1"><\/noscript>/g,
    (_, href) => '<link rel="stylesheet" href="' + href + '">');
  return t;
}

function apply(html, criticalCss) {
  let t = revert(html);
  const links = readLinks(t);
  if (!links.length) throw new Error('no local stylesheet links found');

  for (const l of links) {
    const plain = '<link rel="stylesheet" href="' + l.href + '">';
    if (t.indexOf(plain) === -1) throw new Error('expected plain link for ' + l.href);
    t = t.replace(plain, () =>
      '<link rel="preload" as="style" href="' + l.href + '" onload="this.onload=null;this.rel=\'stylesheet\'">\n'
      + '<noscript><link rel="stylesheet" href="' + l.href + '"></noscript>');
  }

  const block = START + '\n<style>' + criticalCss + '</style>\n' + END + '\n';
  const first = '<link rel="preload" as="style" href="' + links[0].href + '"';
  const at = t.indexOf(first);
  if (at === -1) throw new Error('could not locate the first stylesheet link');
  return t.slice(0, at) + block + t.slice(at);
}

/* ---------- main ---------- */
(async () => {
  let chromium, CleanCSS;
  try { chromium = require('playwright').chromium; CleanCSS = require('clean-css'); }
  catch (e) {
    console.error('needs playwright and clean-css:\n  npm install --no-save playwright clean-css');
    process.exit(1);
  }

  const { server, port } = await serve();
  const browser = await chromium.launch();
  const results = [];

  for (const file of PAGES) {
    const route = '/' + file.replace(/\.html$/, '').replace(/^index$/, '');
    const union = new Set();
    let hrefs = [];

    for (const w of WIDTHS) {
      const ctx = await browser.newContext({ viewport: { width: w, height: w < 500 ? 844 : 900 } });
      const p = await ctx.newPage();
      await p.goto('http://127.0.0.1:' + port + route, { waitUntil: 'load', timeout: 60000 });
      await p.waitForTimeout(1200);                    // let main.js paint the header
      /* One sample is not reproducible. These pages animate: the landing page's scene
         toggles classes as it runs (.lp .node-label.synced .num appeared in one build
         and not the next), and a single measurement captures whichever frame it landed
         on, which made --check flake about one run in six. Sample a fixed number of
         times across a fixed window instead, long enough to cover a loop of the scene.
         A convergence test was tried first and was worse: it can fall quiet in a gap
         between states and stop early, so the sample count itself varied. */
      for (let i = 0; i < SAMPLES; i++) {
        const r = await p.evaluate(collect);
        r.keep.forEach(k => union.add(k));
        hrefs = r.hrefs;
        if (i < SAMPLES - 1) await p.waitForTimeout(SAMPLE_GAP);
      }
      await ctx.close();
    }

    const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const p = await ctx.newPage();
    await p.goto('http://127.0.0.1:' + port + route, { waitUntil: 'load', timeout: 60000 });
    await p.waitForTimeout(800);
    const raw = await p.evaluate(emit, [...union]);
    await ctx.close();

    const min = new CleanCSS({ level: 1 }).minify(raw);
    if (min.errors.length) throw new Error(min.errors.join('; '));
    const css = min.styles;

    let html = fs.readFileSync(file, 'utf8');
    const crlf = html.indexOf(CR + LF) !== -1;
    if (crlf) html = html.split(CR + LF).join(LF);
    let next = apply(html, css);
    if (crlf) next = next.split(LF).join(CR + LF);

    const current = fs.readFileSync(file, 'utf8');
    const local = hrefs.filter(h => h && h.indexOf('/assets/css/') !== -1);
    results.push({ file, css: css.length, raw: raw.length, sheets: local.length, changed: current !== next });
    if (!CHECK && current !== next) fs.writeFileSync(file, next);
  }

  await browser.close();
  server.close();

  console.log('  page                       sheets   critical CSS   inlined');
  for (const r of results) {
    console.log('  ' + r.file.padEnd(26) + String(r.sheets).padStart(5)
      + '   ' + ((r.raw / 1024).toFixed(1) + 'K raw').padStart(12)
      + '   ' + ((r.css / 1024).toFixed(1) + 'K').padStart(7));
  }

  if (CHECK) {
    const stale = results.filter(r => r.changed).map(r => r.file);
    if (stale.length) {
      console.error('\ncritical CSS is out of date in: ' + stale.join(', ')
        + '\nrun node scripts/build-critical-css.js');
      process.exit(1);
    }
    console.log('\ncritical CSS is current');
  }
})().catch(e => { console.error(e); process.exit(1); });
